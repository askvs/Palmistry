# Interpretations engine: rule-based fallback responses must surface as readable text,
# never as raw fallback JSON (regression: palm page showed the rule payload verbatim).
import json

import groq

from app.services.interpretation.llm_adapter import LLMResponse, reset_llm_adapter
from app.services.interpretation.engine import (
    generate_palm_interpretation,
    generate_reading_synthesis,
    generate_tarot_interpretation,
)

PALM_DATA = {
    "palm_shape": {"element": "Water"},
    "lines": [
        {
            "name": "Life Line",
            "confidence": 0.6,
            "variation_type": "close_to_thumb",
            "interpretation": "Steady pace.",
        }
    ],
    "mounts": [{"name": "Mount of Jupiter", "prominence": "prominent", "score": 0.82}],
    "metadata": {"overall_confidence": 0.75},
    "finger_structure": {"digit_ratio_2d_4d": 0.96},
}

TAROT_DATA = {
    "spread_name": "Three Card",
    "card_count": 1,
    "cards": [
        {"card_name": "The Star", "orientation": "upright", "arcana": "major", "keywords": ["hope"]}
    ],
    "metadata": {"overall_relevance": 0.7},
}

RULE_NARRATIVE = (
    "This interpretation was generated by the deterministic rule engine because "
    "the provider rate limit was reached. Please try again in a moment."
)
RULE_GUIDANCE = [
    "Reflect on the symbols drawn and consider how they mirror your current life chapter.",
    "Approach the reading as interpretive guidance for self-reflection, not as guaranteed fact.",
]
RULE_PAYLOAD = {
    "rule_based": True,
    "request_digest": "abc123abc123",
    "provider": "groq",
    "model": "qwen/qwen3.8-27b",
    "guidance": RULE_GUIDANCE,
    "narrative": RULE_NARRATIVE,
    "disclaimer": "All insights are offered strictly for interpretive guidance.",
}


def _stub_engine_adapter(monkeypatch, response):
    """Make the engine consume a canned LLM response without touching any provider."""

    class _StubAdapter:
        def complete(self, **kwargs):
            return response

    monkeypatch.setattr(
        "app.services.interpretation.engine.get_llm_adapter", lambda: _StubAdapter()
    )


def _rule_response():
    return LLMResponse(
        json.dumps(RULE_PAYLOAD),
        model="qwen/qwen3.8-27b",
        provider="groq",
        rule_based=True,
    )


class TestRuleBasedFallbackMapping:
    def test_rule_based_palm_result_shows_narrative_as_body(self, monkeypatch):
        _stub_engine_adapter(monkeypatch, _rule_response())

        result = generate_palm_interpretation(PALM_DATA)

        assert result["rule_based"] is True
        assert result["body"] == RULE_NARRATIVE
        assert result["guidance"] == RULE_GUIDANCE
        assert not result["body"].lstrip().startswith("{")

    def test_rule_based_palm_result_never_leaks_json_without_narrative(self, monkeypatch):
        payload = {key: value for key, value in RULE_PAYLOAD.items() if key != "narrative"}
        response = LLMResponse(
            json.dumps(payload), model="qwen/qwen3.8-27b", provider="groq", rule_based=True
        )
        _stub_engine_adapter(monkeypatch, response)

        result = generate_palm_interpretation(PALM_DATA)

        assert result["body"]
        assert not result["body"].lstrip().startswith("{")

    def test_plain_text_rule_fallback_is_kept_as_body(self, monkeypatch):
        text = (
            "[rule-based fallback] request_digest=abc123\n"
            "This response was generated by the deterministic rule engine."
        )
        response = LLMResponse(
            text, model="rulebook-1.0.0", provider="rule_based", rule_based=True
        )
        _stub_engine_adapter(monkeypatch, response)

        result = generate_palm_interpretation(PALM_DATA)

        assert result["body"].startswith("[rule-based fallback]")

    def test_rule_based_tarot_result_maps_narrative(self, monkeypatch):
        _stub_engine_adapter(monkeypatch, _rule_response())

        result = generate_tarot_interpretation(TAROT_DATA)

        assert result["rule_based"] is True
        assert result["deep_narrative"] == RULE_NARRATIVE
        assert result["wisdom_points"] == RULE_GUIDANCE
        assert not result["deep_narrative"].lstrip().startswith("{")

    def test_rule_based_synthesis_result_maps_narrative(self, monkeypatch):
        _stub_engine_adapter(monkeypatch, _rule_response())

        result = generate_reading_synthesis(PALM_DATA, TAROT_DATA)

        assert result["rule_based"] is True
        assert result["life_narrative"] == RULE_NARRATIVE
        assert result["integrated_guidance"] == RULE_GUIDANCE
        assert not result["life_narrative"].lstrip().startswith("{")


class TestRateLimitedProviderEndToEnd:
    def test_rate_limited_groq_yields_readable_body_not_json(self, monkeypatch):
        """The original bug: Groq 429 -> rule fallback -> raw JSON displayed as the body."""

        class _RateLimit429Error(Exception):
            def __init__(self, message="Error code: 429 - Rate limit reached"):
                super().__init__(message)
                self.status_code = 429

        class _Always429Completions:
            def create(self, **kwargs):
                raise _RateLimit429Error()

        class _Always429Chat:
            completions = _Always429Completions()

        class _Always429GroqClient:
            def __init__(self, api_key):
                self.api_key = api_key
                self.chat = _Always429Chat()

        monkeypatch.setattr(
            "app.services.interpretation.llm_adapter.settings.OPENAI_API_KEY", ""
        )
        monkeypatch.setattr(
            "app.services.interpretation.llm_adapter.settings.GROQ_API_KEY", "test-groq-key"
        )
        monkeypatch.setattr(
            "app.services.interpretation.llm_adapter.time.sleep", lambda _seconds: None
        )
        monkeypatch.setattr(groq, "Groq", _Always429GroqClient, raising=False)
        reset_llm_adapter()

        result = generate_palm_interpretation(PALM_DATA)

        assert result["rule_based"] is True
        assert result["provider"] == "groq"
        assert not result["body"].lstrip().startswith("{")
        assert "rate limit" in result["body"].lower()
        reset_llm_adapter()
